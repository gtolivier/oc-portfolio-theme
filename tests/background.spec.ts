test('with JavaScript, on the French home page, once the section "Parcours" comes into view, each key figure passes through a number between 0 and its own, shown alone without the rest of its value, before it shows its full value', async ({
  page,
}) => {
  /* Time stands still from before the page loads, until the test advances it, step by step, to
     watch the figures count as they go. */
  await stopClockBeforeLoad(page);
  await page.goto('/fr/');
  const section = backgroundSection(page);
  /* Below the first screen on load, so that the figures start from 0. */
  await expect(section).toHaveCount(1);
  await expect(section).not.toBeInViewport();
  await section.scrollIntoViewIfNeeded();
  await expect(section, 'the section has come into view').toBeInViewport();
  /* Each figure: its number, the rest of its value ("+" for "20+", nothing for "350") and its
     label, as the screen shows them, whitespace excluded. */
  const figures = KEY_FIGURES.map(({ value, label }) => {
    const target = parseInt(value, 10);
    const rest = value.slice(String(target).length);
    const shownLabel = labelOnScreen(label);
    return {
      value,
      target,
      rest,
      /* A whole number (no digit before it) right before the label, with or without the rest of
         the value in between. */
      shown: new RegExp(`(?<!\\d)(\\d+)(${literally(rest)})?${shownLabel}`, 'u'),
      full: new RegExp(`(?<!\\d)${literally(value)}${shownLabel}`, 'u'),
      between: [] as number[],
      partialWithRest: [] as string[],
    };
  });
  /* Every 25 ms, for at most 5 s, until both figures show their full value: what the visitor sees
     on screen. Text that only assistive technologies get does not count. */
  let shown = '';
  for (let elapsed = 0; elapsed <= 5000; elapsed += 25) {
    if (elapsed > 0) await page.clock.runFor(25);
    shown = await textOnScreen(section);
    for (const figure of figures) {
      const match = figure.shown.exec(shown);
      if (!match) continue;
      const number = parseInt(match[1], 10);
      if (number <= 0 || number >= figure.target) continue;
      if (match[2]) figure.partialWithRest.push(`${match[1]}${match[2]}`);
      else figure.between.push(number);
    }
    if (figures.every((figure) => figure.full.test(shown))) break;
  }
  for (const figure of figures) {
    expect(
      figure.between.length,
      `the figure "${figure.value}" showed, alone, some number between 1 and ${figure.target - 1}`,
    ).toBeGreaterThan(0);
    expect(
      figure.partialWithRest,
      `the figure "${figure.value}" never showed a number below ${figure.target} with "${figure.rest}"`,
    ).toEqual([]);
    expect(shown, `the figure "${figure.value}" then shows its full value next to its label`).toMatch(figure.full);
  }
});

/* Where something starts on the page (its left edge and its top), in page coordinates, so that
   scrolling does not move it. */
type PagePosition = { left: number; top: number };

/* The number a key figure shows on screen (its first run of digits among the text that shows, so
   not the text that only assistive technologies get) and where it starts on the page; null when
   it shows no number. */
async function shownNumber(figure: Locator): Promise<{ digits: string; position: PagePosition } | null> {
  return figure.evaluate((root) => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const parent = node.parentElement;
      if (!parent || !parent.checkVisibility({ opacityProperty: true, visibilityProperty: true })) continue;
      const match = /\d+/.exec(node.textContent ?? '');
      if (!match) continue;
      const range = document.createRange();
      range.setStart(node, match.index);
      range.setEnd(node, match.index + match[0].length);
      const box = range.getBoundingClientRect();
      if (box.width === 0 || box.height === 0) continue;
      return { digits: match[0], position: { left: box.left + window.scrollX, top: box.top + window.scrollY } };
    }
    return null;
  });
}

/* Where an element starts on the page. */
async function pagePosition(element: Locator): Promise<PagePosition> {
  return element.evaluate((el) => {
    const box = el.getBoundingClientRect();
    return { left: box.left + window.scrollX, top: box.top + window.scrollY };
  });
}

test('with JavaScript, on the French home page, while the key figures of the section "Parcours" climb to their value, neither their labels nor the numbers they show move: each starts where it started before the climb', async ({
  page,
}) => {
  /* Time stands still from before the page loads, until the test advances it, step by step, to
     watch the figures as they climb. */
  await stopClockBeforeLoad(page);
  await page.goto('/fr/');
  await page.evaluate(() => document.fonts.ready);
  const section = backgroundSection(page);
  /* Below the first screen on load, so that the figures start from 0. */
  await expect(section).toHaveCount(1);
  await expect(section).not.toBeInViewport();
  const figures = KEY_FIGURES.map(({ value, label }) => ({
    value,
    label,
    target: String(parseInt(value, 10)),
    figure: section.getByRole('term').filter({ hasText: value }),
    labelElement: section.getByText(label, { exact: true }),
  }));
  /* Before the climb: each figure shows 0; where its 0 and its label start. */
  const before: { number: PagePosition; label: PagePosition }[] = [];
  for (const { value, label, figure, labelElement } of figures) {
    await expect(figure, `the figure "${value}"`).toHaveCount(1);
    await expect(labelElement, `the label "${label}"`).toBeVisible();
    await expect
      .poll(async () => (await shownNumber(figure))?.digits, { message: `number the figure "${value}" shows` })
      .toBe('0');
    before.push({ number: (await shownNumber(figure))!.position, label: await pagePosition(labelElement) });
  }
  await section.scrollIntoViewIfNeeded();
  await expect(section, 'the section has come into view').toBeInViewport();
  /* Every 25 ms, for at most 5 s, until every figure shows its full number: where each shown
     number and each label start, kept each time one has moved by more than a pixel (subpixel
     rounding aside) from where it started before the climb. */
  const moves: string[] = [];
  const moved = (now: PagePosition, then: PagePosition) =>
    Math.abs(now.left - then.left) > 1 || Math.abs(now.top - then.top) > 1;
  let allFull = false;
  for (let elapsed = 0; elapsed <= 5000 && !allFull; elapsed += 25) {
    if (elapsed > 0) await page.clock.runFor(25);
    allFull = true;
    for (const [index, { value, label, target, figure, labelElement }] of figures.entries()) {
      const shown = await shownNumber(figure);
      const labelNow = await pagePosition(labelElement);
      if (moved(labelNow, before[index].label)) {
        moves.push(
          `at ${elapsed} ms, the label "${label}" at ${JSON.stringify(labelNow)}, against ${JSON.stringify(before[index].label)}`,
        );
      }
      if (!shown) {
        moves.push(`at ${elapsed} ms, the figure "${value}" shows no number`);
        allFull = false;
        continue;
      }
      if (moved(shown.position, before[index].number)) {
        moves.push(
          `at ${elapsed} ms, the number ${shown.digits} of the figure "${value}" at ${JSON.stringify(shown.position)}, against ${JSON.stringify(before[index].number)}`,
        );
      }
      if (shown.digits !== target) allFull = false;
    }
  }
  expect(allFull, 'every figure has come to show its full number').toBe(true);
  expect(moves, 'labels and shown numbers that moved during the climb').toEqual([]);
});

/* What assistive technologies get for the key figures of a section: the terms and definitions of
   its accessibility tree, in order, each as its role then its text. */
async function exposedKeyFigures(section: Locator): Promise<string[]> {
  const accessibilityTree = await section.ariaSnapshot();
  return accessibilityTree
    .split('\n')
    .map((line) => /^\s*- (term|definition)\b(.*)$/.exec(line))
    .filter((match) => match !== null)
    .map(([, role, rest]) => {
      /* "- term: 20+", "- term: \"350\"" (a number, quoted), "- term \"20+\"" or
         "- term \"20+\": 20+" alike: the role, then its name and its text, if any, unquoted. */
      const [, name, text] = /^(?:\s+("(?:[^"\\]|\\.)*"))?(?::\s*(.*))?$/.exec(rest) ?? [, undefined, rest];
      const unquoted = (part: string) => (part.startsWith('"') ? (JSON.parse(part) as string) : part).trim();
      const texts = [name, text].filter((part) => part !== undefined && part !== '').map((part) => unquoted(part!));
      return `${role}: ${texts.join(' ')}`;
    });
}

test('with JavaScript, on the French home page, before, during and after the climb of the key figures of the section "Parcours", assistive technologies get each figure as its full value then its label, never another number', async ({
  page,
}) => {
  /* Time stands still from before the page loads, until the test advances it, step by step, to
     check what assistive technologies get as the figures climb. */
  await stopClockBeforeLoad(page);
  await page.goto('/fr/');
  const section = backgroundSection(page);
  /* Below the first screen on load, so that the figures start from 0. */
  await expect(section).toHaveCount(1);
  await expect(section).not.toBeInViewport();
  const figures = KEY_FIGURES.map(({ value }) => ({
    value,
    target: parseInt(value, 10),
    figure: section.getByRole('term').filter({ hasText: value }),
  }));
  /* Each figure, exactly: its full value as the term, then its label as the definition; nothing
     else, so neither a 0, nor a number on its way, nor a value given twice can pass. */
  const expected = KEY_FIGURES.flatMap(({ value, label }) => [`term: ${value}`, `definition: ${label}`]);
  /* The numbers the figures show on screen, in order: null for a figure that shows none. */
  const shownNumbers = async () =>
    Promise.all(figures.map(async ({ figure }) => (await shownNumber(figure))?.digits ?? null));

  /* Before: the section has not come into view, each figure shows 0. */
  await expect
    .poll(shownNumbers, { message: 'numbers the figures show before the section comes into view' })
    .toEqual(figures.map(() => '0'));
  expect(await exposedKeyFigures(section), 'what assistive technologies get while the figures show 0').toEqual(
    expected,
  );

  /* During: every 25 ms, for at most 5 s, until every figure shows its full number; what
     assistive technologies get is kept each time it is not the expected one. */
  await section.scrollIntoViewIfNeeded();
  await expect(section, 'the section has come into view').toBeInViewport();
  const wrong: string[] = [];
  let climbing = 0;
  let allFull = false;
  for (let elapsed = 0; elapsed <= 5000 && !allFull; elapsed += 25) {
    if (elapsed > 0) await page.clock.runFor(25);
    const shown = await shownNumbers();
    const exposed = await exposedKeyFigures(section);
    if (JSON.stringify(exposed) !== JSON.stringify(expected)) {
      wrong.push(`at ${elapsed} ms, while the figures show ${JSON.stringify(shown)}: ${JSON.stringify(exposed)}`);
    }
    if (
      figures.some(({ target }, index) => {
        const number = parseInt(shown[index] ?? '', 10);
        return number > 0 && number < target;
      })
    ) {
      climbing += 1;
    }
    allFull = figures.every(({ target }, index) => shown[index] === String(target));
  }
  expect(climbing, 'moments when a figure showed a number between 0 and its own').toBeGreaterThan(0);
  expect(allFull, 'every figure has come to show its full number').toBe(true);
  expect(wrong, 'what assistive technologies got during the climb, when not every full value and label').toEqual([]);

  /* After: every figure shows its full value. */
  expect(
    await exposedKeyFigures(section),
    'what assistive technologies get once the figures show their full value',
  ).toEqual(expected);
});

/* Every 50 ms, for 2 s on the page's real clock (longer than a count or a climb takes): what the
   visitor sees on screen in a section, kept each time it does not match the pattern given. */
async function textsOnScreenNotMatching(section: Locator, pattern: RegExp): Promise<string[]> {
  const notMatching: string[] = [];
  for (let elapsed = 0; elapsed <= 2000; elapsed += 50) {
    if (elapsed > 0) await section.page().waitForTimeout(50);
    const shown = await textOnScreen(section);
    if (!pattern.test(shown)) notMatching.push(shown);
  }
  return notMatching;
}

