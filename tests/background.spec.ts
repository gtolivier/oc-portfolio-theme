/* The background section of a home page, in its main content: a region named by its title, the
   French one unless another is given. */
function backgroundSection(page: Page, title = 'Parcours'): Locator {
  return page.getByRole('main').getByRole('region', { name: title, exact: true });
}

test('on the French home page, a section "Parcours" comes right after the section "Projets sélectionnés", its heading showing the section number "02 //" before its title, while assistive technologies get the title alone', async ({
  page,
}) => {
  await page.goto('/fr/');
  const main = page.getByRole('main');
  const projects = main.getByRole('region', { name: 'Projets sélectionnés', exact: true });
  const section = backgroundSection(page);
  await expect(projects).toHaveCount(1);
  await expect(section).toHaveCount(1);
  /* Right after: among the regions of the main content, in document order and leaving out those
     nested in the projects section, the one that follows the projects section is "Parcours". */
  const regions = await main.getByRole('region').elementHandles();
  const projectsElement = await projects.elementHandle();
  const backgroundElement = await section.elementHandle();
  const order = await page.evaluate(
    ([list, projectsRegion, backgroundRegion]) => {
      const outer = list.filter((region) => region === projectsRegion || !projectsRegion.contains(region));
      const next = outer[outer.indexOf(projectsRegion) + 1];
      return { projectsFound: outer.includes(projectsRegion), nextIsBackground: next === backgroundRegion };
    },
    [regions, projectsElement!, backgroundElement!] as const,
  );
  expect(order.projectsFound, 'the projects section is a region of the main content').toBe(true);
  expect(order.nextIsBackground, 'the region right after "Projets sélectionnés" is "Parcours"').toBe(true);
  /* On screen: the decorative number, then the title, and nothing else, whether the number is
     text in the page or generated by the stylesheet. */
  const heading = section.getByRole('heading', { level: 2 });
  await expect(heading).toBeVisible();
  await expect.poll(() => displayedText(heading), 'text displayed by the heading').toMatch(/^02 ?\/\/ ?Parcours$/);
  /* For assistive technologies: the title alone, for the heading and the region it names. */
  await expect(heading).toHaveAccessibleName('Parcours');
  await expect(section).toHaveAccessibleName('Parcours');
});

